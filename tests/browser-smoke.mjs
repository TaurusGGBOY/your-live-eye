// Optional real-browser acceptance: install Playwright or set PW_MODULE.
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PW_MODULE || 'playwright');
const url=process.argv[2] || 'https://your-live-eye-demo.pages.dev/';
const output=process.argv[3] || '/tmp/codextmp/your-live-eye-browser';
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH || undefined});
const report={url,checks:[],errors:[]};
const check=(name,condition)=>{if(!condition)throw new Error(name);report.checks.push(name);};
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',e=>report.errors.push(e.message));
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('.severity-badge').first().waitFor();
 const state=await page.evaluate(()=>({title:document.title,total:document.querySelector('#message-count').textContent,date:document.querySelector('#date').value,bins:document.querySelectorAll('.time-bin').length,heading:document.querySelector('#critical-title').textContent,topics:document.querySelector('#reaction-title').textContent,scores:[...document.querySelectorAll('.severity-badge')].map(x=>Number(x.textContent)),low:[...document.querySelectorAll('.critical-quote-low .severity-badge')].map(x=>Number(x.textContent))}));
 report.snapshot=state;
 check('Demo identity and event count',state.title.includes('明前奶绿') && state.total.replaceAll(',','')==='58919' && state.date==='2026-10-25');
 check('61 five-minute bins',state.bins===61);
 check('Quarrel heading',state.heading==='争吵言论');
 check('173 retained scores and low-score styling',state.scores.length===173 && state.scores.every(n=>n>=1&&n<=100) && state.low.length===42 && state.low.every(n=>n<50));
 check('Reviewed semantic topics',state.topics==='玩梗话题');
 const insights=await (await page.request.get(new URL('/insights/2026-10-25.json',url).href)).json();
 const expectedTopics=[...insights.reaction_topics].sort((a,b)=>a.first_reaction.ts-b.first_reaction.ts);
 const shownTitles=await page.locator('.reaction-story strong').allTextContents();
 check('All confirmed topics in time order',shownTitles.length>2 && JSON.stringify(shownTitles)===JSON.stringify(expectedTopics.map(x=>x.title)));
 const expectedQuotes=insights.period_insights.flatMap(x=>x.critical_quotes).sort((a,b)=>a.ts-b.ts);
 const shownQuotes=await page.locator('.quote-source').evaluateAll(nodes=>nodes.map(x=>x.title.replace(' · 在 Danmakus 按内容与时间查看出处','')));
 check('Selected quarrel texts retained in time order',JSON.stringify(shownQuotes)===JSON.stringify(expectedQuotes.map(x=>x.text)));
 await page.locator('.meme-evidence summary').first().click();
 check('Evidence expands',await page.locator('.meme-evidence[open]').count()===1);
 await page.screenshot({path:output+'/evidence.jpg',type:'jpeg',quality:88});
 await page.locator('.meme-evidence summary').first().click();
 await page.screenshot({path:output+'/desktop.jpg',type:'jpeg',quality:88});
 await page.locator('.meme-time').first().click();
 check('Topic time selects real period',await page.locator('#all-day').isVisible());
 await page.screenshot({path:output+'/period.jpg',type:'jpeg',quality:88});
 await page.locator('#all-day').click();
 await page.locator('.meme-time').last().click();
 check('Last topic remains reachable',await page.locator('#all-day').isVisible());
 await page.locator('#all-day').click();
 check('Return restores all topics',await page.locator('.reaction-story').count()===shownTitles.length);
 await page.locator('.time-bin').first().click();
 check('Chart selects five-minute period',await page.locator('#all-day').isVisible());
 await page.locator('#all-day').click();
 await page.locator('#open-calendar').click();
 check('Calendar opens',await page.locator('#calendar-dialog').evaluate(e=>e.open));
 await page.locator('#calendar-close').click();
 await page.locator('#changelog-button').click();
 check('Release notes contain 0.4.1',(await page.locator('#changelog-dialog').innerText()).includes('0.4.1'));
 await page.locator('#changelog-close').click();
 const [repo]=await Promise.all([page.waitForEvent('popup'),page.locator('#github-link').click()]);
 await repo.waitForLoadState('domcontentloaded');check('GitHub link opens repository',repo.url().startsWith('https://github.com/TaurusGGBOY/your-live-eye'));await repo.close();
 await page.reload({waitUntil:'domcontentloaded'});await page.locator('.severity-badge').first().waitFor();
 check('Ordinary refresh retains data',(await page.locator('#message-count').innerText())===state.total);
 await page.goto(new URL('/?date=2026-10-25&window=day',url).href,{waitUntil:'domcontentloaded'});await page.locator('.severity-badge').first().waitFor();
 check('Original dated link works',(await page.locator('#critical-title').innerText())==='争吵言论');
 for(const [width,height] of [[1280,600],[390,844]]){
  await page.setViewportSize({width,height});
  check('No horizontal overflow '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 }
 await page.screenshot({path:output+'/mobile.jpg',type:'jpeg',quality:88});
 check('No browser exceptions',report.errors.length===0);
 console.log(JSON.stringify({checks:report.checks.length,events:state.total,topics:state.topics,errors:report.errors}));
}finally{await fs.writeFile(output+'/report.json',JSON.stringify(report,null,2));await browser.close();}
